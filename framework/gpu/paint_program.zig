//! paint_program.zig — editable strokes over an explicit authored raster baseline.
//!
//! Every authoring dab/fill on the model paint target is appended here as a
//! resolution-independent op. The program remains the editable durable recipe; the
//! package additionally stores the exact raster UNDER it so generated bases, part
//! colors, and externally edited PNGs survive a cold replay without flattening later
//! strokes into that image.
//!
//! req_2672 grows the program into the painter's WHOLE editing model:
//!
//!   • STROKES — ops are grouped into strokes (pointer-down→up = one stroke; a fill
//!     click = one stroke). Each committed stroke is ONE undo unit in the stroke
//!     journal (undoStroke/redoStroke): undo drops the last unit and RE-RUNS the
//!     program onto the atlas — the program is the truth, so undo is replay, never a
//!     pixel diff. A baseline atlas snapshot (taken before the first stroke) anchors
//!     the replay so paint that predates the program (part tints, the atlas base)
//!     survives every undo. Package v3 persists that baseline beside the program as
//!     raster-base.png; it is source texture data, never a screenshot of the editor.
//!
//!   • LAYERS — the stroke program IS the layer system (USER ASK req_2672: "i want to
//!     write some stupid shit like 'i like it' first and then fuck off everything
//!     behind it"). A layer is an ordered stroke GROUP (id, name, visible); every
//!     stroke records the ACTIVE layer's id; replay runs layers bottom→top, skipping
//!     invisible ones. Delete/reorder/merge are pure program edits + one replay — no
//!     pixel-layer compositor anywhere. Structural layer ops journal as undo units in
//!     the same stroke journal, so undoing a layer-delete restores it wholesale.
//!     Visibility is the exception (req_2752): the eye is VIEW state — never journaled,
//!     and undo/redo carry the live eye toggles across (see adoptSnapshot).
//!
//!   • HIDE-STABLE KEYS — v1 recorded dabs by DISPLAYED face index, which shifts when
//!     a part hides (a program saved while a part was hidden replayed misindexed).
//!     v2 ops key by (AUTHORED GROUP id, intra-group face ordinal): group ids survive
//!     hide/show verbatim and a group's faces keep their relative order, so the key
//!     resolves to the right face in whatever face order the mesh currently displays.
//!     v1 blobs still load (converted to one "Layer 1" stroke on the current mesh).
//!
//! Why it beats storing the atlas: a dither brush's scatter is the worst case for RLE
//! and bloats a PNG, but it is generated by a few numbers — so we keep the numbers (the
//! ops), never the scatter (the pixels). Shader inks embed their WGSL + params, so the
//! blob is SELF-CONTAINED: replay re-bakes the material with no catalog.
//!
//! Recording lives in the authoring entry points (3d.zig paintStampAt/paintAt); replay
//! calls model_paint directly and suppresses recording, so it never re-records itself.

