var g_have_active: bool = false;
var g_active_is_mat: bool = false;
var g_active_mat: u16 = 0;
var g_active_rgb: [3]u8 = .{ 0, 0, 0 };

var g_recording: bool = true; // false during replay, so replay never re-records

// ── Baseline atlas (undo anchor + package raster base) ──────────────────────────────
// Captured once, right before the first program op lands (or right after a loaded
// program's base-clear). replayAll restores it first, so paint that is NOT in the
// program — part tints laid at load, the chosen atlas base — survives undo instead of
// being wiped by the clear. The package writer persists this exact buffer separately
// from the stroke recipe, so an external texture edit remains the base on cold reopen.
// Dropped on reset; a dimension mismatch (detail changed) falls back to clearAtlas + base.
var g_baseline: ?[]u8 = null;

fn dropBaseline() void {
    if (g_baseline) |b| alloc.free(b);
    g_baseline = null;
}

fn captureBaselineIfNeeded() void {
    if (g_baseline != null) return;
    const a = model_paint.atlas() orelse return;
    g_baseline = alloc.dupe(u8, a.rgba) catch null;
}

fn forceBaselineCapture() void {
    dropBaseline();
    captureBaselineIfNeeded();
}

/// An externally edited atlas PNG is a deliberate raster bake. Keep the layer
/// names, retire the old stroke recipe/history, and make the imported pixels the
/// baseline beneath every stroke authored from this point onward.
pub fn adoptCurrentAtlasAsBaseline() void {
    _ = endStrokeUnit();
    snapshotLayersForCarry();
    reset();
    forceBaselineCapture();
}

/// Read-only package boundary for the exact raster beneath the recorded strokes.
/// Callers must copy/encode before any paint mutation.
pub fn baseline() ?[]const u8 {
    return g_baseline;
}

// ── Hide-stable face keys: (authored group, intra-group ordinal) ────────────────────
// The ordinal cache maps displayed face → its rank among faces sharing its authored
// group, in display order. Rebuilt lazily whenever the face count changes; 3d.zig also
// invalidates it on every layout/grouping refresh (groups can change at a stable count).
var g_ord_cache: ?[]u32 = null;

pub fn invalidateFaceKeys() void {
    if (g_ord_cache) |c| alloc.free(c);
    g_ord_cache = null;
}

fn faceOrdinals() ?[]const u32 {
    const fc = model_paint.faceCount();
    if (fc == 0) return null;
    if (g_ord_cache) |c| {
        if (c.len == fc) return c;
        invalidateFaceKeys();
    }
    const ords = alloc.alloc(u32, fc) catch return null;
    var counts = std.AutoHashMapUnmanaged(u32, u32){};
    defer counts.deinit(alloc);
    var f: u32 = 0;
    while (f < fc) : (f += 1) {
        const g = model_source.faceGroupOf(f);
        if (g == model_source.NO_FACE_GROUP) {
            ords[f] = f; // ungrouped: the raw index is the (only) stable key we have
            continue;
        }
        const gop = counts.getOrPut(alloc, g) catch {
            ords[f] = f;
            continue;
        };
        if (!gop.found_existing) gop.value_ptr.* = 0;
        ords[f] = gop.value_ptr.*;
        gop.value_ptr.* += 1;
    }
    g_ord_cache = ords;
    return ords;
}

const FaceKey = struct { group: u32, ord: u32 };

fn faceKeyOf(face: u32) FaceKey {
    const grp = model_source.faceGroupOf(face);
    if (grp == model_source.NO_FACE_GROUP) return .{ .group = NO_GROUP, .ord = face };
    const ords = faceOrdinals() orelse return .{ .group = NO_GROUP, .ord = face };
    if (face >= ords.len) return .{ .group = NO_GROUP, .ord = face };
    return .{ .group = grp, .ord = ords[face] };
}

// Replay-side resolver: (group, ord) → the face displayed NOW. Built once per replay.
const Resolver = struct {
    map: std.AutoHashMapUnmanaged(u64, u32) = .{},
    fn deinit(self: *Resolver) void {
        self.map.deinit(alloc);
    }
};

fn resolverKey(group: u32, ord: u32) u64 {
    return (@as(u64, group) << 32) | ord;
}

fn buildResolver() Resolver {
    var res = Resolver{};
    const fc = model_paint.faceCount();
    var counts = std.AutoHashMapUnmanaged(u32, u32){};
    defer counts.deinit(alloc);
    var f: u32 = 0;
    while (f < fc) : (f += 1) {
        const g = model_source.faceGroupOf(f);
        if (g == model_source.NO_FACE_GROUP) continue; // resolved as raw index below
        const gop = counts.getOrPut(alloc, g) catch continue;
        if (!gop.found_existing) gop.value_ptr.* = 0;
        res.map.put(alloc, resolverKey(g, gop.value_ptr.*), f) catch {};
        gop.value_ptr.* += 1;
    }
    return res;
}

/// The face a recorded key lands on TODAY, or null (its part is hidden / deleted —
/// the op skips this replay and comes back when the faces do).
fn resolveFace(res: *const Resolver, group: u32, ord: u32) ?u32 {
    if (group == NO_GROUP) {
        return if (ord < model_paint.faceCount()) ord else null;
    }
    return res.map.get(resolverKey(group, ord));
}

// ── Memory helpers ──────────────────────────────────────────────────────────────────
fn freeMatList(list: *std.ArrayList(MatRecipe)) void {
    for (list.items) |m| {
        alloc.free(m.key);
        alloc.free(m.wgsl);
        alloc.free(m.data);
    }
    list.clearRetainingCapacity();
}

fn freeMats() void {
    freeMatList(&g_mats);
}

fn freeLayerList(list: *std.ArrayList(Layer)) void {
    for (list.items) |l| alloc.free(l.name);
    list.clearRetainingCapacity();
}

fn freeStrokeList(list: *std.ArrayList(Stroke)) void {
    for (list.items) |s| alloc.free(s.ops);
    list.clearRetainingCapacity();
}

// ── Layer table ─────────────────────────────────────────────────────────────────────
fn layerIndexOf(id: u32) ?usize {
    for (g_layers.items, 0..) |l, i| {
        if (l.id == id) return i;
    }
    return null;
}

fn appendLayer(name_src: ?[]const u8) ?u32 {
    const id = g_next_layer_id;
    var buf: [24]u8 = undefined;
    const fallback = std.fmt.bufPrint(&buf, "Layer {d}", .{id}) catch "Layer";
    const name = alloc.dupe(u8, name_src orelse fallback) catch return null;
    g_layers.append(alloc, .{ .id = id, .name = name, .visible = true }) catch {
        alloc.free(name);
        return null;
    };
    g_next_layer_id += 1;
    return id;
}

/// A program always paints ONTO a layer — materialize "Layer 1" the moment anything
/// needs one (first stroke, first layer op, a v1 blob load).
fn ensureLayers() void {
    if (g_layers.items.len > 0) return;
    if (appendLayer(null)) |id| g_active_layer = id;
}

// ── Layer carry across an EDIT mesh replace ─────────────────────────────────────────
// Every topology op replaces the resident mesh, which resets this module (strokes can't
// survive a topology change — the atlas texel carry preserves the pixels). The layer
// TABLE is the user's organizational setup though, and losing it to an eye toggle would
// be gratuitous: 3d.zig stashes it here right before the replace; the reset consumes it.
var g_carry_layers: ?[]Layer = null;
var g_carry_active: u32 = 0;
var g_carry_next: u32 = 1;
// A topology replace normally starts a genuinely new program because face identity may
// have changed. A part APPEND is different: every existing (group, ordinal) key remains
// valid and only fresh groups are added. That operation arms this one-shot before
// setPaintTarget() resets the module, keeping the exact live program + paint journal.
// The atlas itself is carried by model_paint; the old baseline is deliberately dropped
// because its packed UV layout belongs to the pre-append mesh. A later replay rebuilds
// the same strokes over the carried atlas base on the new layout.
var g_carry_program_once: bool = false;

pub fn carryProgramAcrossNextTarget() void {
    _ = endStrokeUnit();
    g_carry_program_once = true;
}

pub fn cancelProgramCarry() void {
    g_carry_program_once = false;
}

pub fn snapshotLayersForCarry() void {
    dropLayerCarry();
    if (g_layers.items.len == 0) return;
    const copy = alloc.alloc(Layer, g_layers.items.len) catch return;
    var n: usize = 0;
    for (g_layers.items) |l| {
        const nm = alloc.dupe(u8, l.name) catch break;
        copy[n] = .{ .id = l.id, .name = nm, .visible = l.visible };
        n += 1;
    }
    if (n != copy.len) {
        for (copy[0..n]) |l| alloc.free(l.name);
        alloc.free(copy);
        return;
    }
    g_carry_layers = copy;
    g_carry_active = g_active_layer;
    g_carry_next = g_next_layer_id;
}

fn dropLayerCarry() void {
    if (g_carry_layers) |ls| {
        for (ls) |l| alloc.free(l.name);
        alloc.free(ls);
    }
    g_carry_layers = null;
}

// ── The stroke journal (undo/redo) ──────────────────────────────────────────────────
// Each unit (committed stroke, structural layer op) pushes a deep-copy SNAPSHOT of the
// program state taken BEFORE the unit — layers, active id, strokes. Undo swaps the live
// state with the top snapshot and replays; the program is small (numbers, not pixels),
// so whole-state snapshots are cheap and uniformly correct for every op kind.
const Snapshot = struct {
    label: []const u8, // static string — the unit that FOLLOWED this state
    layers: []Layer,
    active: u32,
    next_id: u32,
    strokes: []Stroke,
};

/// Opaque, exact paint-authoring state carried by the model journal across UV and
/// texture transactions. The raster lives in the model journal separately; this
/// snapshot owns everything that makes that raster editable again: layers, strokes,
/// shader recipes, the raster baseline, and the applicable stroke undo/redo branches.
/// Callers can clone, byte-count, adopt, or free it but cannot couple themselves to
/// the paint program's internal representation.
pub const JournalState = opaque {};

const JournalStateData = struct {
    layers: std.ArrayList(Layer) = .empty,
    active: u32 = 0,
    next_id: u32 = 1,
    strokes: std.ArrayList(Stroke) = .empty,
    mats: std.ArrayList(MatRecipe) = .empty,
    undo: std.ArrayList(Snapshot) = .empty,
    redo: std.ArrayList(Snapshot) = .empty,
    baseline: ?[]u8 = null,
    have_active: bool = false,
    active_is_mat: bool = false,
    active_mat: u16 = 0,
    active_rgb: [3]u8 = .{ 0, 0, 0 },

    fn deinit(self: *JournalStateData) void {
        freeLayerList(&self.layers);
        self.layers.deinit(alloc);
        freeStrokeList(&self.strokes);
        self.strokes.deinit(alloc);
        freeMatList(&self.mats);
        self.mats.deinit(alloc);
        freeSnapshotStack(&self.undo);
        self.undo.deinit(alloc);
        freeSnapshotStack(&self.redo);
        self.redo.deinit(alloc);
        if (self.baseline) |pixels| alloc.free(pixels);
        self.baseline = null;
    }
};

// No entry-count cap: the byte budget is the only wall (req_4700).
const JOURNAL_BYTE_BUDGET: usize = 32 * 1024 * 1024;

var g_undo_snaps: std.ArrayList(Snapshot) = .empty;
var g_redo_snaps: std.ArrayList(Snapshot) = .empty;

fn snapshotBytes(s: *const Snapshot) usize {
    var total: usize = @sizeOf(Snapshot);
    for (s.layers) |l| total += @sizeOf(Layer) + l.name.len;
    for (s.strokes) |st| total += @sizeOf(Stroke) + st.ops.len;
    return total;
}

fn freeSnapshot(s: *Snapshot) void {
    for (s.layers) |l| alloc.free(l.name);
    alloc.free(s.layers);
    for (s.strokes) |st| alloc.free(st.ops);
    alloc.free(s.strokes);
}

fn freeSnapshotStack(stack: *std.ArrayList(Snapshot)) void {
    for (stack.items) |*s| freeSnapshot(s);
    stack.clearRetainingCapacity();
}

fn cloneLayers(source: []const Layer) ?std.ArrayList(Layer) {
    var copy: std.ArrayList(Layer) = .empty;
    for (source) |layer| {
        const name = alloc.dupe(u8, layer.name) catch {
            freeLayerList(&copy);
            copy.deinit(alloc);
            return null;
        };
        copy.append(alloc, .{ .id = layer.id, .name = name, .visible = layer.visible }) catch {
            alloc.free(name);
            freeLayerList(&copy);
            copy.deinit(alloc);
            return null;
        };
    }
    return copy;
}

fn cloneStrokes(source: []const Stroke) ?std.ArrayList(Stroke) {
    var copy: std.ArrayList(Stroke) = .empty;
    for (source) |stroke| {
        const ops = alloc.dupe(u8, stroke.ops) catch {
            freeStrokeList(&copy);
            copy.deinit(alloc);
            return null;
        };
        copy.append(alloc, .{ .layer = stroke.layer, .ops = ops }) catch {
            alloc.free(ops);
            freeStrokeList(&copy);
            copy.deinit(alloc);
            return null;
        };
    }
    return copy;
}

fn cloneMats(source: []const MatRecipe) ?std.ArrayList(MatRecipe) {
    var copy: std.ArrayList(MatRecipe) = .empty;
    for (source) |recipe| {
        const key = alloc.dupe(u8, recipe.key) catch {
            freeMatList(&copy);
            copy.deinit(alloc);
            return null;
        };
        const wgsl = alloc.dupe(u8, recipe.wgsl) catch {
            alloc.free(key);
            freeMatList(&copy);
            copy.deinit(alloc);
            return null;
        };
        const data = alloc.dupe(f32, recipe.data) catch {
            alloc.free(key);
            alloc.free(wgsl);
            freeMatList(&copy);
            copy.deinit(alloc);
            return null;
        };
        copy.append(alloc, .{ .key = key, .wgsl = wgsl, .data = data, .tiles = recipe.tiles }) catch {
            alloc.free(key);
            alloc.free(wgsl);
            alloc.free(data);
            freeMatList(&copy);
            copy.deinit(alloc);
            return null;
        };
    }
    return copy;
}

fn snapshotFrom(
    layers_source: []const Layer,
    active: u32,
    next_id: u32,
    strokes_source: []const Stroke,
    label: []const u8,
) ?Snapshot {
    var layers = cloneLayers(layers_source) orelse return null;
    var strokes = cloneStrokes(strokes_source) orelse {
        freeLayerList(&layers);
        layers.deinit(alloc);
        return null;
    };
    const layer_slice = layers.toOwnedSlice(alloc) catch {
        freeLayerList(&layers);
        layers.deinit(alloc);
        freeStrokeList(&strokes);
        strokes.deinit(alloc);
        return null;
    };
    const stroke_slice = strokes.toOwnedSlice(alloc) catch {
        for (layer_slice) |layer| alloc.free(layer.name);
        alloc.free(layer_slice);
        freeStrokeList(&strokes);
        strokes.deinit(alloc);
        return null;
    };
    return .{ .label = label, .layers = layer_slice, .active = active, .next_id = next_id, .strokes = stroke_slice };
}

fn cloneSnapshot(source: *const Snapshot) ?Snapshot {
    return snapshotFrom(source.layers, source.active, source.next_id, source.strokes, source.label);
}

fn cloneSnapshotStack(source: []const Snapshot) ?std.ArrayList(Snapshot) {
    var copy: std.ArrayList(Snapshot) = .empty;
    for (source) |*snapshot| {
        const cloned = cloneSnapshot(snapshot) orelse {
            freeSnapshotStack(&copy);
            copy.deinit(alloc);
            return null;
        };
        copy.append(alloc, cloned) catch {
            var owned = cloned;
            freeSnapshot(&owned);
            freeSnapshotStack(&copy);
            copy.deinit(alloc);
            return null;
        };
    }
    return copy;
}

fn cloneJournalStateData(source: *const JournalStateData) ?JournalStateData {
    var copy = JournalStateData{
        .active = source.active,
        .next_id = source.next_id,
        .have_active = source.have_active,
        .active_is_mat = source.active_is_mat,
        .active_mat = source.active_mat,
        .active_rgb = source.active_rgb,
    };
    var complete = false;
    defer if (!complete) copy.deinit();
    copy.layers = cloneLayers(source.layers.items) orelse return null;
    copy.strokes = cloneStrokes(source.strokes.items) orelse return null;
    copy.mats = cloneMats(source.mats.items) orelse return null;
    copy.undo = cloneSnapshotStack(source.undo.items) orelse return null;
    copy.redo = cloneSnapshotStack(source.redo.items) orelse return null;
    if (source.baseline) |pixels| copy.baseline = alloc.dupe(u8, pixels) catch return null;
    complete = true;
    return copy;
}

fn snapshotsContainStrokes(snapshots: []const Snapshot) bool {
    for (snapshots) |snapshot| {
        if (snapshot.strokes.len > 0) return true;
    }
    return false;
}

fn captureJournalStateData(discard_redo_branch: bool) ?JournalStateData {
    // A flattened/imported atlas commonly has an empty program but a full-size
    // baseline equal to the live raster. Do not copy those megabytes into every UV
    // gesture: with no current or historical strokes, the next stroke can recapture
    // the unchanged live atlas losslessly. A non-empty current/undo/redo recipe still
    // carries the exact baseline it needs for later replay.
    const needs_baseline = g_strokes.items.len > 0 or
        snapshotsContainStrokes(g_undo_snaps.items) or
        snapshotsContainStrokes(g_redo_snaps.items);
    var source = JournalStateData{
        .layers = g_layers,
        .active = g_active_layer,
        .next_id = g_next_layer_id,
        .strokes = g_strokes,
        .mats = g_mats,
        .undo = g_undo_snaps,
        .redo = g_redo_snaps,
        .baseline = if (needs_baseline) g_baseline else null,
        .have_active = g_have_active,
        .active_is_mat = g_active_is_mat,
        .active_mat = g_active_mat,
        .active_rgb = g_active_rgb,
    };
    var captured = cloneJournalStateData(&source) orelse return null;
    if (discard_redo_branch) {
        // A UV/texture command is a NEW document action. Standard branch semantics
        // discard paint redo that already existed before it; undoing the UV command
        // must not resurrect that abandoned branch. A journal SWAP passes false so
        // paint units already undone after this UV unit remain available after redo.
        freeSnapshotStack(&captured.redo);
    }
    return captured;
}

fn journalStateData(state: *const JournalState) *const JournalStateData {
    return @ptrCast(@alignCast(state));
}

fn journalStateDataMut(state: *JournalState) *JournalStateData {
    return @ptrCast(@alignCast(state));
}

fn ownJournalState(data: JournalStateData) ?*JournalState {
    const owned = alloc.create(JournalStateData) catch {
        var discarded = data;
        discarded.deinit();
        return null;
    };
    owned.* = data;
    return @ptrCast(owned);
}

/// Capture the exact editable paint state for an undo/redo swap. Any half-open stroke
/// is first committed, matching the existing save/undo boundary; both history sides
/// are retained because either may contain paint units adjacent to the UV unit.
pub fn journalStateCapture() ?*JournalState {
    _ = endStrokeUnit();
    const data = captureJournalStateData(false) orelse return null;
    return ownJournalState(data);
}

/// Capture the pre-state of a newly committed UV/texture action. Unlike a history
/// swap, a new action abandons any paint-redo branch that existed before it.
pub fn journalStateCaptureForNewAction() ?*JournalState {
    _ = endStrokeUnit();
    const data = captureJournalStateData(true) orelse return null;
    return ownJournalState(data);
}

/// Deep-clone a retained state before a journal install. This makes restore allocation
/// transactional: all fallible work completes before UVs or atlas pixels are mutated.
pub fn journalStateClone(state: *const JournalState) ?*JournalState {
    const data = cloneJournalStateData(journalStateData(state)) orelse return null;
    return ownJournalState(data);
}

pub fn journalStateBytes(state: *const JournalState) usize {
    const data = journalStateData(state);
    var total: usize = @sizeOf(JournalStateData);
    for (data.layers.items) |layer| total += @sizeOf(Layer) + layer.name.len;
    for (data.strokes.items) |stroke| total += @sizeOf(Stroke) + stroke.ops.len;
    for (data.mats.items) |recipe| {
        total += @sizeOf(MatRecipe) + recipe.key.len + recipe.wgsl.len + recipe.data.len * @sizeOf(f32);
    }
    for (data.undo.items) |*snapshot| total += snapshotBytes(snapshot);
    for (data.redo.items) |*snapshot| total += snapshotBytes(snapshot);
    if (data.baseline) |pixels| total += pixels.len;
    return total;
}

pub fn journalStateFree(state: *JournalState) void {
    const data = journalStateDataMut(state);
    data.deinit();
    alloc.destroy(data);
}

/// Install a state previously cloned for restore. This consumes `state` and performs
/// no allocation, so once the raster/UV half of a journal restore succeeds the program
/// half cannot fail and leave a split document.
pub fn journalStateAdopt(state: *JournalState) void {
    const data = journalStateDataMut(state);

    // Layer visibility is view state (req_2752), not document history. Carry the live
    // eye toggles, names, and active target for ids that exist on both sides, exactly
    // like a non-journaled panel edit. Swapping owned name buffers keeps adoption
    // allocation-free: the discarded snapshot names are freed with the old live list.
    const live_active = g_active_layer;
    var preserve_live_active = false;
    for (data.layers.items) |*layer| {
        if (layerIndexOf(layer.id)) |current| {
            layer.visible = g_layers.items[current].visible;
            const snapshot_name = layer.name;
            layer.name = g_layers.items[current].name;
            g_layers.items[current].name = snapshot_name;
            preserve_live_active = preserve_live_active or layer.id == live_active;
        }
    }

    g_open.clearRetainingCapacity();
    g_open_fill_seen.clearRetainingCapacity();
    g_open_live = false;
    g_open_label = "stroke";
    g_recording = true;

    freeLayerList(&g_layers);
    g_layers.deinit(alloc);
    g_layers = data.layers;
    data.layers = .empty;
    freeStrokeList(&g_strokes);
    g_strokes.deinit(alloc);
    g_strokes = data.strokes;
    data.strokes = .empty;
    freeMats();
    g_mats.deinit(alloc);
    g_mats = data.mats;
    data.mats = .empty;
    freeSnapshotStack(&g_undo_snaps);
    g_undo_snaps.deinit(alloc);
    g_undo_snaps = data.undo;
    data.undo = .empty;
    freeSnapshotStack(&g_redo_snaps);
    g_redo_snaps.deinit(alloc);
    g_redo_snaps = data.redo;
    data.redo = .empty;
    dropBaseline();
    g_baseline = data.baseline;
    data.baseline = null;

    g_active_layer = if (preserve_live_active) live_active else data.active;
    g_next_layer_id = data.next_id;
    g_have_active = data.have_active;
    g_active_is_mat = data.active_is_mat;
    g_active_mat = data.active_mat;
    g_active_rgb = data.active_rgb;
    dropLayerCarry();
    g_carry_program_once = false;
    invalidateFaceKeys();

    data.deinit();
    alloc.destroy(data);
}

fn snapshotCurrent(label: []const u8) ?Snapshot {
    return snapshotFrom(g_layers.items, g_active_layer, g_next_layer_id, g_strokes.items, label);
}

/// Push the CURRENT state as the pre-state of the unit about to apply. New units clear
/// the redo stack (standard journal semantics). Trimmed oldest-first by count + bytes.
fn pushUndo(label: []const u8) void {
    const snap = snapshotCurrent(label) orelse return;
    freeSnapshotStack(&g_redo_snaps);
    g_undo_snaps.append(alloc, snap) catch {
        var s = snap;
        freeSnapshot(&s);
        return;
    };
    var total: usize = 0;
    for (g_undo_snaps.items) |*s| total += snapshotBytes(s);
    while (total > JOURNAL_BYTE_BUDGET and g_undo_snaps.items.len > 1) {
        var old = g_undo_snaps.orderedRemove(0);
        total -= snapshotBytes(&old);
        freeSnapshot(&old);
    }
}

/// Adopt a snapshot as the live program state (takes ownership of its allocations).
/// Visibility is VIEW state, not history (req_2752): a layer that exists on both sides
/// keeps its LIVE eye toggle — undo/redo restore strokes/structure, never flip the eye.
fn adoptSnapshot(s: Snapshot) void {
    for (s.layers) |*l| {
        if (layerIndexOf(l.id)) |cur| l.visible = g_layers.items[cur].visible;
    }
    freeLayerList(&g_layers);
    g_layers.appendSlice(alloc, s.layers) catch {
        for (s.layers) |l| alloc.free(l.name);
    };
    alloc.free(s.layers);
    freeStrokeList(&g_strokes);
    g_strokes.appendSlice(alloc, s.strokes) catch {
        for (s.strokes) |st| alloc.free(st.ops);
    };
    alloc.free(s.strokes);
    g_active_layer = s.active;
    g_next_layer_id = s.next_id;
}

pub fn historyCounts() [2]u32 {
    return .{ @intCast(g_undo_snaps.items.len), @intCast(g_redo_snaps.items.len) };
}

pub fn undoLabel() []const u8 {
    if (g_undo_snaps.items.len == 0) return "";
    return g_undo_snaps.items[g_undo_snaps.items.len - 1].label;
}

pub fn redoLabel() []const u8 {
    if (g_redo_snaps.items.len == 0) return "";
    return g_redo_snaps.items[g_redo_snaps.items.len - 1].label;
}

/// Undo one unit: swap the live program with the top pre-state snapshot and re-run the
/// program onto the atlas. Commits any open stroke first (an undo mid-drag undoes THAT
/// stroke — never a stale older one). False when there's nothing to undo.
pub fn undoStroke(io: std.Io, environ: *const std.process.Environ.Map) bool {
    _ = endStrokeUnit();
    if (g_undo_snaps.items.len == 0) return false;
    const pre = g_undo_snaps.items[g_undo_snaps.items.len - 1];
    g_undo_snaps.items.len -= 1;
    if (snapshotCurrent(pre.label)) |cur| {
        g_redo_snaps.append(alloc, cur) catch {
            var c = cur;
            freeSnapshot(&c);
        };
    }
    adoptSnapshot(pre);
    replayAll(io, environ);
    return true;
}

pub fn redoStroke(io: std.Io, environ: *const std.process.Environ.Map) bool {
    _ = endStrokeUnit();
    if (g_redo_snaps.items.len == 0) return false;
    const post = g_redo_snaps.items[g_redo_snaps.items.len - 1];
    g_redo_snaps.items.len -= 1;
    if (snapshotCurrent(post.label)) |cur| {
        g_undo_snaps.append(alloc, cur) catch {
            var c = cur;
            freeSnapshot(&c);
        };
    }
    adoptSnapshot(post);
    replayAll(io, environ);
    return true;
}

// ── Reset / lifecycle ───────────────────────────────────────────────────────────────
/// Wipe the recorded program (new paint target, or a cleared painting). Consumes a
/// pending layer-table carry (snapshotLayersForCarry) so an edit-mesh replace keeps the
/// user's layer setup while dropping the strokes the new topology invalidated.
pub fn reset() void {
    if (g_carry_program_once) {
        g_carry_program_once = false;
        // replaceActiveEditMesh also takes the ordinary layer-only snapshot. The full
        // program already owns those layers, so discard that redundant deep copy.
        dropLayerCarry();
        g_open.clearRetainingCapacity();
        g_open_fill_seen.clearRetainingCapacity();
        g_open_live = false;
        g_have_active = false;
        dropBaseline();
        invalidateFaceKeys();
        return;
    }
    g_open.clearRetainingCapacity();
    g_open_live = false;
    freeStrokeList(&g_strokes);
    freeLayerList(&g_layers);
    freeSnapshotStack(&g_undo_snaps);
    freeSnapshotStack(&g_redo_snaps);
    freeMats();
    g_have_active = false;
    g_active_is_mat = false;
    dropBaseline();
    invalidateFaceKeys();
    g_active_layer = 0;
    g_next_layer_id = 1;
    if (g_carry_layers) |ls| {
        g_layers.appendSlice(alloc, ls) catch {
            for (ls) |l| alloc.free(l.name);
            alloc.free(ls);
            g_carry_layers = null;
            return;
        };
        alloc.free(ls);
        g_carry_layers = null;
        g_active_layer = g_carry_active;
        g_next_layer_id = g_carry_next;
        if (layerIndexOf(g_active_layer) == null and g_layers.items.len > 0) {
            g_active_layer = g_layers.items[g_layers.items.len - 1].id;
        }
    }
}

// ── Recording ───────────────────────────────────────────────────────────────────────
fn appendOpenU16(v: u16) void {
    var b: [2]u8 = undefined;
    std.mem.writeInt(u16, &b, v, .little);
    g_open.appendSlice(alloc, &b) catch {};
}
fn appendOpenU32(v: u32) void {
    var b: [4]u8 = undefined;
    std.mem.writeInt(u32, &b, v, .little);
    g_open.appendSlice(alloc, &b) catch {};
}
fn appendOpenF32(v: f32) void {
    appendOpenU32(@bitCast(v));
}

/// Register (dedup by key) a shader ink and mark it active. Called when JS sets a bucket;
/// the WGSL + params are captured so the program is self-contained.
pub fn activateMaterial(key: []const u8, wgsl: []const u8, data: []const f32, tiles: f32) void {
    var idx: u16 = 0;
    var found = false;
    for (g_mats.items, 0..) |m, i| {
        if (std.mem.eql(u8, m.key, key)) {
            idx = @intCast(i);
            found = true;
            break;
        }
    }
    if (!found) {
        const k = alloc.dupe(u8, key) catch return;
        const w = alloc.dupe(u8, wgsl) catch {
            alloc.free(k);
            return;
        };
        const d = alloc.dupe(f32, data) catch {
            alloc.free(k);
            alloc.free(w);
            return;
        };
        g_mats.append(alloc, .{ .key = k, .wgsl = w, .data = d, .tiles = tiles }) catch {
            alloc.free(k);
            alloc.free(w);
            alloc.free(d);
            return;
        };
        idx = @intCast(g_mats.items.len - 1);
    }
    g_active_is_mat = true;
    g_active_mat = idx;
    g_have_active = false; // force the next dab to emit this ink
}

/// The active ink returns to flat colour (JS cleared the material).
pub fn deactivateMaterial() void {
    g_active_is_mat = false;
    g_have_active = false;
}

fn emitInk(mat: bool, rgb: [3]u8) void {
    if (mat) {
        if (!g_have_active or !g_active_is_mat) {
            g_open.append(alloc, OP_INK_MATERIAL) catch {};
            appendOpenU16(g_active_mat);
            g_open_fill_seen.clearRetainingCapacity();
            g_have_active = true;
            g_active_is_mat = true;
        }
    } else if (!g_have_active or g_active_is_mat or !std.mem.eql(u8, &g_active_rgb, &rgb)) {
        g_open.append(alloc, OP_INK_COLOR) catch {};
        g_open.appendSlice(alloc, &rgb) catch {};
        g_open_fill_seen.clearRetainingCapacity();
        g_have_active = true;
        g_active_is_mat = false;
        g_active_rgb = rgb;
    }
}

/// Called by the authoring entry points (3d.zig paintStampAt/paintAt) BEFORE the first
/// texel of a recorded gesture lands. The undo baseline must hold the PRE-stroke atlas;
/// recordDab/recordFill fire only AFTER the dab already painted, so anchoring there
/// leaked the first dab's texels into the baseline (they survived layer hide/delete).
pub fn beginRecordedOp() void {
    if (!g_recording) return;
    ensureLayers();
    captureBaselineIfNeeded();
}

fn openUnit(label: []const u8) void {
    if (g_open_live) return;
    ensureLayers();
    captureBaselineIfNeeded(); // anchor undo BEFORE the first program op mutates the atlas
    g_open.clearRetainingCapacity();
    g_open_fill_seen.clearRetainingCapacity();
    g_open_live = true;
    g_open_label = label;
    g_have_active = false; // each stroke's op stream re-states its ink (self-contained)
}

/// Record one free-form dab, keyed hide-stable (authored group + intra-group ordinal).
pub fn recordDab(face: u32, u: f32, v: f32, radius: f32, flow: f32, mat: bool, rgb: [3]u8) void {
    if (!g_recording) return;
    openUnit("stroke");
    emitInk(mat, rgb);
    g_open_fill_seen.clearRetainingCapacity();
    const key = faceKeyOf(face);
    g_open.append(alloc, OP_DAB) catch {};
    appendOpenU32(key.group);
    appendOpenU32(key.ord);
    appendOpenF32(u);
    appendOpenF32(v);
    appendOpenF32(radius);
    appendOpenF32(flow);
}

/// Record a SHAPED dab (req_2831): OP_DAB's fields + the brush footprint spec, so
/// program replay reproduces rakes/fans/sprays exactly (grain seeds derive from u/v).
pub fn recordDabShaped(face: u32, u: f32, v: f32, radius: f32, flow: f32, mat: bool, rgb: [3]u8, spec: model_paint.BrushShape) void {
    if (!g_recording) return;
    openUnit("stroke");
    emitInk(mat, rgb);
    g_open_fill_seen.clearRetainingCapacity();
    const key = faceKeyOf(face);
    g_open.append(alloc, OP_DAB_BLENDED) catch {};
    appendOpenU32(key.group);
    appendOpenU32(key.ord);
    appendOpenF32(u);
    appendOpenF32(v);
    appendOpenF32(radius);
    appendOpenF32(flow);
    appendOpenU32(spec.kind);
    appendOpenF32(spec.hardness);
    appendOpenF32(spec.angle_rad);
    appendOpenF32(spec.aspect);
    appendOpenF32(spec.scatter);
    appendOpenU32(spec.blend);
}

/// Record one whole-face fill (same hide-stable key).
pub fn recordFill(face: u32, mat: bool, rgb: [3]u8) void {
    if (!g_recording) return;
    openUnit("fill");
    emitInk(mat, rgb);
    const key = faceKeyOf(face);
    const seen_key = resolverKey(key.group, key.ord);
    if (g_open_fill_seen.contains(seen_key)) return; // idempotent repeat — record nothing
    g_open_fill_seen.put(alloc, seen_key, {}) catch {}; // OOM: fall through, over-record safely
    g_open.append(alloc, OP_FILL) catch {};
    appendOpenU32(key.group);
    appendOpenU32(key.ord);
}

/// Record one bounded closed pen fill in normalized authored-island space.
pub fn recordPolygon(face: u32, points: []const f32, flow: f32, blend: u8, mat: bool, rgb: [3]u8) void {
    if (!g_recording or points.len < 6 or points.len % 2 != 0) return;
    const point_count = @min(points.len / 2, MAX_POLYGON_POINTS);
    openUnit("pen fill");
    emitInk(mat, rgb);
    g_open_fill_seen.clearRetainingCapacity();
    const key = faceKeyOf(face);
    g_open.append(alloc, OP_POLYGON) catch {};
    appendOpenU32(key.group);
    appendOpenU32(key.ord);
    appendOpenU32(@intCast(point_count));
    appendOpenF32(flow);
    var index: usize = 0;
    while (index < MAX_POLYGON_POINTS * 2) : (index += 1) {
        appendOpenF32(if (index < point_count * 2) points[index] else 0.0);
    }
    appendOpenU32(if (blend <= 7) blend else 0);
}

/// Commit the open stroke unit: pointer-up (or any journal/serialize boundary). The
/// pre-state snapshot journals FIRST — the open ops aren't in g_strokes yet, so the
/// current committed state IS the pre-state. False when nothing was recorded.
pub fn endStrokeUnit() bool {
    if (!g_open_live) return false;
    g_open_live = false;
    if (g_open.items.len == 0) return false;
    const ops = alloc.dupe(u8, g_open.items) catch {
        g_open.clearRetainingCapacity();
        return false;
    };
    g_open.clearRetainingCapacity();
    pushUndo(g_open_label);
    g_strokes.append(alloc, .{ .layer = g_active_layer, .ops = ops }) catch {
        alloc.free(ops);
        return false;
    };
    return true;
}

/// Whether the just-committed live atlas writes need the canonical bottom→top
/// replay before they are presented.  Top-layer visible strokes are already in
/// composite order; every other case must re-lay once at pointer-up.
pub fn activeLayerNeedsCompositeReplay() bool {
    const active_index = layerIndexOf(g_active_layer) orelse return true;
    var visible_above = false;
    for (g_layers.items[active_index + 1 ..]) |layer| {
        if (layer.visible) {
            visible_above = true;
            break;
        }
    }
    return paint_ops.strokeCommitNeedsReplay(g_layers.items[active_index].visible, visible_above);
}

pub fn isEmpty() bool {
    return g_strokes.items.len == 0 and (!g_open_live or g_open.items.len == 0);
}

