pub const LayerInfo = struct { id: u32, name: []const u8, visible: bool, strokes: u32 };

pub fn layerCount() usize {
    return g_layers.items.len;
}

pub fn layerInfoAt(i: usize) LayerInfo {
    const l = g_layers.items[i];
    var n: u32 = 0;
    for (g_strokes.items) |st| {
        if (st.layer == l.id) n += 1;
    }
    return .{ .id = l.id, .name = l.name, .visible = l.visible, .strokes = n };
}

pub fn activeLayerId() u32 {
    return g_active_layer;
}

/// Add a fresh layer on TOP and make it active. Journaled. Returns the new id (0 = fail).
/// No replay — an empty layer changes no pixels.
pub fn layerAdd() u32 {
    _ = endStrokeUnit();
    ensureLayers();
    pushUndo("add layer");
    const id = appendLayer(null) orelse return 0;
    g_active_layer = id;
    return id;
}

/// Delete a layer AND its strokes (the "fuck off everything behind it" verb). Journaled —
/// undo restores the layer and every stroke, because the program is the truth. Replays.
pub fn layerDelete(io: std.Io, environ: *const std.process.Environ.Map, id: u32) bool {
    _ = endStrokeUnit();
    const idx = layerIndexOf(id) orelse return false;
    pushUndo("delete layer");
    const removed = g_layers.orderedRemove(idx);
    alloc.free(removed.name);
    var w: usize = 0;
    for (g_strokes.items) |st| {
        if (st.layer == id) {
            alloc.free(st.ops);
            continue;
        }
        g_strokes.items[w] = st;
        w += 1;
    }
    g_strokes.items.len = w;
    if (g_layers.items.len == 0) ensureLayers(); // painting always has a target layer
    if (layerIndexOf(g_active_layer) == null) {
        g_active_layer = g_layers.items[g_layers.items.len - 1].id;
    }
    replayAll(io, environ);
    return true;
}

/// Move a layer one step toward the top (up=true → composites later) or bottom. Journaled.
pub fn layerMove(io: std.Io, environ: *const std.process.Environ.Map, id: u32, up: bool) bool {
    _ = endStrokeUnit();
    const idx = layerIndexOf(id) orelse return false;
    if (up and idx + 1 >= g_layers.items.len) return false;
    if (!up and idx == 0) return false;
    pushUndo("reorder layer");
    const other = if (up) idx + 1 else idx - 1;
    const tmp = g_layers.items[idx];
    g_layers.items[idx] = g_layers.items[other];
    g_layers.items[other] = tmp;
    replayAll(io, environ);
    return true;
}

/// Show/hide a layer's strokes. NOT journaled (req_2752) — visibility is a VIEW toggle,
/// not a program edit: no stroke is added or removed, the eye just filters the composite.
/// Replays (the atlas is derived, so the composite must re-lay), and adoptSnapshot keeps
/// the live eye state through undo/redo so history never flips what you're looking at.
pub fn layerSetVisible(io: std.Io, environ: *const std.process.Environ.Map, id: u32, on: bool) bool {
    _ = endStrokeUnit();
    const idx = layerIndexOf(id) orelse return false;
    if (g_layers.items[idx].visible == on) return true;
    g_layers.items[idx].visible = on;
    replayAll(io, environ);
    return true;
}

/// Route new strokes to this layer. NOT journaled — picking a target changes no pixels,
/// and journaling it would bury real undo units under selection noise.
pub fn layerSetActive(id: u32) bool {
    if (layerIndexOf(id) == null) return false;
    _ = endStrokeUnit();
    g_active_layer = id;
    return true;
}

/// Rename in place. NOT journaled (metadata, no composite change).
pub fn layerRename(id: u32, name: []const u8) bool {
    const idx = layerIndexOf(id) orelse return false;
    const trimmed = std.mem.trim(u8, name, " \t\r\n");
    if (trimmed.len == 0) return false;
    const nm = alloc.dupe(u8, trimmed[0..@min(trimmed.len, 48)]) catch return false;
    alloc.free(g_layers.items[idx].name);
    g_layers.items[idx].name = nm;
    return true;
}

/// Fold a layer's strokes into the layer BELOW it and drop the layer. The merged strokes
/// keep their composite position: below's strokes stay first, the merged layer's follow.
/// Journaled; replays. False on the bottom layer (nothing below to merge into).
pub fn layerMergeDown(io: std.Io, environ: *const std.process.Environ.Map, id: u32) bool {
    _ = endStrokeUnit();
    const idx = layerIndexOf(id) orelse return false;
    if (idx == 0) return false;
    pushUndo("merge layers");
    const below = g_layers.items[idx - 1].id;
    // Rebuild the stroke list so the merged layer's composite order survives inside ONE
    // layer id: others (chronological) + below's strokes + the merged layer's strokes.
    var rebuilt: std.ArrayList(Stroke) = .empty;
    var below_strokes: std.ArrayList(Stroke) = .empty;
    var top_strokes: std.ArrayList(Stroke) = .empty;
    defer rebuilt.deinit(alloc);
    defer below_strokes.deinit(alloc);
    defer top_strokes.deinit(alloc);
    var ok = true;
    for (g_strokes.items) |st| {
        if (st.layer == below) {
            below_strokes.append(alloc, st) catch {
                ok = false;
            };
        } else if (st.layer == id) {
            top_strokes.append(alloc, .{ .layer = below, .ops = st.ops }) catch {
                ok = false;
            };
        } else {
            rebuilt.append(alloc, st) catch {
                ok = false;
            };
        }
    }
    if (ok) {
        rebuilt.appendSlice(alloc, below_strokes.items) catch {
            ok = false;
        };
    }
    if (ok) {
        rebuilt.appendSlice(alloc, top_strokes.items) catch {
            ok = false;
        };
    }
    if (!ok or rebuilt.items.len != g_strokes.items.len) {
        // Allocation trouble mid-rebuild — keep the original list untouched (the pushed
        // journal entry is a harmless no-op undo) rather than risk dropped strokes.
        return false;
    }
    @memcpy(g_strokes.items, rebuilt.items);
    const removed = g_layers.orderedRemove(idx);
    alloc.free(removed.name);
    if (g_active_layer == id) g_active_layer = below;
    replayAll(io, environ);
    return true;
}

// ── Replay ──────────────────────────────────────────────────────────────────────────
const Cursor = struct {
    b: []const u8,
    p: usize = 0,
    fn u8v(c: *Cursor) ?u8 {
        if (c.p >= c.b.len) return null;
        const v = c.b[c.p];
        c.p += 1;
        return v;
    }
    fn u16v(c: *Cursor) ?u16 {
        if (c.p + 2 > c.b.len) return null;
        const v = std.mem.readInt(u16, c.b[c.p..][0..2], .little);
        c.p += 2;
        return v;
    }
    fn u32v(c: *Cursor) ?u32 {
        if (c.p + 4 > c.b.len) return null;
        const v = std.mem.readInt(u32, c.b[c.p..][0..4], .little);
        c.p += 4;
        return v;
    }
    fn f32v(c: *Cursor) ?f32 {
        const u = c.u32v() orelse return null;
        return @bitCast(u);
    }
    fn bytes(c: *Cursor, n: usize) ?[]const u8 {
        if (c.p + n > c.b.len) return null;
        const s = c.b[c.p .. c.p + n];
        c.p += n;
        return s;
    }
};

fn bakeMatRecipe(io: std.Io, environ: *const std.process.Environ.Map, key: []const u8, wgsl: []const u8, data: []const f32, tiles: f32) bool {
    const raw = material_tex.bakePixels(io, environ, key, wgsl, data, MAT_BAKE_SIZE) orelse return false;
    defer std.heap.page_allocator.free(raw);
    if (raw.len < 8) return false;
    const w = std.mem.readInt(u32, raw[0..4], .little);
    const h = std.mem.readInt(u32, raw[4..8], .little);
    return model_paint.setMaterialInk(raw[8..], w, h, tiles);
}

// Ink state threads through the caller so consecutive strokes with the same ink don't
// re-bake a material per stroke. Ink ops only STATE intent; flushInk applies the last
// stated ink right before a dab/fill executes, so ink for fully-skipped ops never bakes.
const ReplayInk = struct {
    mat_active: bool = false,
    mat_idx: u16 = std.math.maxInt(u16),
    rgb: [3]u8 = .{ 255, 255, 255 },
    pending_mat: ?u16 = null,
    pending_rgb: ?[3]u8 = null,
};

fn flushInk(io: std.Io, environ: *const std.process.Environ.Map, ink: *ReplayInk) void {
    if (ink.pending_rgb) |c| {
        ink.rgb = c;
        if (ink.mat_active) model_paint.clearMaterialInk();
        ink.mat_active = false;
        ink.pending_rgb = null;
    } else if (ink.pending_mat) |idx| {
        if (!ink.mat_active or ink.mat_idx != idx) {
            const m = g_mats.items[idx];
            ink.mat_active = bakeMatRecipe(io, environ, m.key, m.wgsl, m.data, m.tiles);
            ink.mat_idx = idx;
        }
        ink.pending_mat = null;
    }
}

fn runStrokeOps(io: std.Io, environ: *const std.process.Environ.Map, ops: []const u8, res: *const Resolver, ink: *ReplayInk) void {
    var skips: []usize = &.{};
    var skips_owned = false;
    if (paint_ops.redundantFillOffsets(alloc, ops)) |s| {
        skips = s;
        skips_owned = true;
    } else |_| {}
    defer if (skips_owned) alloc.free(skips);
    var skip_i: usize = 0;
    var c = Cursor{ .b = ops };
    while (c.p < c.b.len) {
        const op_off = c.p;
        const tag = c.u8v() orelse return;
        switch (tag) {
            OP_INK_COLOR => {
                const cc = c.bytes(3) orelse return;
                ink.pending_rgb = .{ cc[0], cc[1], cc[2] };
                ink.pending_mat = null;
            },
            OP_INK_MATERIAL => {
                const idx = c.u16v() orelse return;
                if (idx >= g_mats.items.len) return;
                ink.pending_mat = idx;
                ink.pending_rgb = null;
            },
            OP_DAB => {
                const group = c.u32v() orelse return;
                const ord = c.u32v() orelse return;
                const u = c.f32v() orelse return;
                const v = c.f32v() orelse return;
                const radius = c.f32v() orelse return;
                const flow = c.f32v() orelse return;
                const face = resolveFace(res, group, ord) orelse continue;
                flushInk(io, environ, ink);
                if (ink.mat_active) model_paint.paintStampTex(face, u, v, radius, flow) else model_paint.paintStamp(face, u, v, radius, .{ ink.rgb[0], ink.rgb[1], ink.rgb[2], 255 }, flow);
            },
            OP_DAB_SHAPED => {
                const group = c.u32v() orelse return;
                const ord = c.u32v() orelse return;
                const u = c.f32v() orelse return;
                const v = c.f32v() orelse return;
                const radius = c.f32v() orelse return;
                const flow = c.f32v() orelse return;
                const kind = c.u32v() orelse return;
                const hardness = c.f32v() orelse return;
                const angle = c.f32v() orelse return;
                const aspect = c.f32v() orelse return;
                const scatter = c.f32v() orelse return;
                const face = resolveFace(res, group, ord) orelse continue;
                const spec = model_paint.BrushShape{ .kind = @intCast(@min(kind, 255)), .hardness = hardness, .angle_rad = angle, .aspect = aspect, .scatter = scatter };
                flushInk(io, environ, ink);
                if (ink.mat_active) model_paint.paintStampTexShaped(face, u, v, radius, flow, spec) else model_paint.paintStampShaped(face, u, v, radius, .{ ink.rgb[0], ink.rgb[1], ink.rgb[2], 255 }, flow, spec);
            },
            OP_DAB_BLENDED => {
                const group = c.u32v() orelse return;
                const ord = c.u32v() orelse return;
                const u = c.f32v() orelse return;
                const v = c.f32v() orelse return;
                const radius = c.f32v() orelse return;
                const flow = c.f32v() orelse return;
                const kind = c.u32v() orelse return;
                const hardness = c.f32v() orelse return;
                const angle = c.f32v() orelse return;
                const aspect = c.f32v() orelse return;
                const scatter = c.f32v() orelse return;
                const blend = c.u32v() orelse return;
                const face = resolveFace(res, group, ord) orelse continue;
                const spec = model_paint.BrushShape{
                    .kind = @intCast(@min(kind, 255)),
                    .hardness = hardness,
                    .angle_rad = angle,
                    .aspect = aspect,
                    .scatter = scatter,
                    .blend = @intCast(if (blend <= 7) blend else 0),
                };
                flushInk(io, environ, ink);
                if (ink.mat_active) model_paint.paintStampTexShaped(face, u, v, radius, flow, spec) else model_paint.paintStampShaped(face, u, v, radius, .{ ink.rgb[0], ink.rgb[1], ink.rgb[2], 255 }, flow, spec);
            },
            OP_FILL => {
                const group = c.u32v() orelse return;
                const ord = c.u32v() orelse return;
                if (skip_i < skips.len and skips[skip_i] == op_off) {
                    skip_i += 1;
                    continue;
                }
                const face = resolveFace(res, group, ord) orelse continue;
                // RGB-only fill: replay must not un-glass a face any more than the live fill does (req_2928).
                flushInk(io, environ, ink);
                if (ink.mat_active) model_paint.paintFaceTex(face) else model_paint.paintFaceRgb(face, .{ ink.rgb[0], ink.rgb[1], ink.rgb[2] });
            },
            OP_POLYGON => {
                const group = c.u32v() orelse return;
                const ord = c.u32v() orelse return;
                const count_raw = c.u32v() orelse return;
                const flow = c.f32v() orelse return;
                var points: [MAX_POLYGON_POINTS * 2]f32 = undefined;
                for (&points) |*value| value.* = c.f32v() orelse return;
                const blend = c.u32v() orelse return;
                const count: usize = @intCast(@min(count_raw, @as(u32, MAX_POLYGON_POINTS)));
                if (count < 3) continue;
                const face = resolveFace(res, group, ord) orelse continue;
                flushInk(io, environ, ink);
                _ = model_paint.paintPolygon(
                    face,
                    points[0 .. count * 2],
                    .{ ink.rgb[0], ink.rgb[1], ink.rgb[2], 255 },
                    ink.mat_active,
                    flow,
                    @intCast(if (blend <= 7) blend else 0),
                );
            },
            else => return,
        }
    }
}

/// Re-run the WHOLE program onto the atlas: restore the baseline (or clear + base), then
/// every visible layer's strokes bottom→top, strokes in chronological order inside each
/// layer. The one composite function behind undo/redo and every layer op. Logs its cost —
/// undo must never hitch the frame, and this line is the receipt.
pub fn replayAll(io: std.Io, environ: *const std.process.Environ.Map) void {
    if (g_baseline) |b| {
        if (!model_paint.setAtlas(b)) model_paint.clearAtlas(); // detail changed → base fallback
    } else {
        model_paint.clearAtlas();
    }
    g_recording = false;
    defer g_recording = true;
    var res = buildResolver();
    defer res.deinit();
    var ink = ReplayInk{};
    for (g_layers.items) |lay| {
        if (!lay.visible) continue;
        for (g_strokes.items) |st| {
            if (st.layer != lay.id) continue;
            runStrokeOps(io, environ, st.ops, &res, &ink);
        }
    }
    // Leave the LIVE brush ink the way the user had it — a replay that silently
    // switched the brush to the last replayed ink would betray the next stroke.
    if (g_active_is_mat and g_active_mat < g_mats.items.len) {
        const m = g_mats.items[g_active_mat];
        _ = bakeMatRecipe(io, environ, m.key, m.wgsl, m.data, m.tiles);
    } else {
        model_paint.clearMaterialInk();
    }
}

// ── Serialize ───────────────────────────────────────────────────────────────────────
fn u16le(v: u16) [2]u8 {
    var b: [2]u8 = undefined;
    std.mem.writeInt(u16, &b, v, .little);
    return b;
}
fn u32le(v: u32) [4]u8 {
    var b: [4]u8 = undefined;
    std.mem.writeInt(u32, &b, v, .little);
    return b;
}

// Build the v2 blob body; any allocation error propagates so serialize() can free cleanly.
fn writeBlob(buf: *std.ArrayList(u8)) !void {
    try buf.appendSlice(alloc, &MAGIC);
    try buf.appendSlice(alloc, &u16le(VERSION));
    try buf.appendSlice(alloc, &u16le(@intCast(model_paint.detail())));
    try buf.appendSlice(alloc, &u32le(model_paint.faceCount()));
    try buf.appendSlice(alloc, &u16le(@intCast(g_mats.items.len)));
    for (g_mats.items) |m| {
        try buf.appendSlice(alloc, &u16le(@intCast(m.key.len)));
        try buf.appendSlice(alloc, m.key);
        try buf.appendSlice(alloc, &u32le(@intCast(m.wgsl.len)));
        try buf.appendSlice(alloc, m.wgsl);
        try buf.appendSlice(alloc, &u16le(@intCast(m.data.len)));
        for (m.data) |f| try buf.appendSlice(alloc, &u32le(@bitCast(f)));
        try buf.appendSlice(alloc, &u32le(@bitCast(m.tiles)));
    }
    // Layer table (bottom→top) + the active id, then the stroke list.
    try buf.appendSlice(alloc, &u16le(@intCast(g_layers.items.len)));
    for (g_layers.items) |l| {
        try buf.appendSlice(alloc, &u32le(l.id));
        try buf.append(alloc, @intFromBool(l.visible));
        try buf.appendSlice(alloc, &u16le(@intCast(l.name.len)));
        try buf.appendSlice(alloc, l.name);
    }
    try buf.appendSlice(alloc, &u32le(g_active_layer));
    try buf.appendSlice(alloc, &u32le(@intCast(g_strokes.items.len)));
    for (g_strokes.items) |st| {
        try buf.appendSlice(alloc, &u32le(st.layer));
        try buf.appendSlice(alloc, &u32le(@intCast(st.ops.len)));
        try buf.appendSlice(alloc, st.ops);
    }
}

/// Serialize the program (header + material table + layers + strokes) into a caller-owned
/// blob, or null if nothing was painted (or on allocation failure). Commits any open
/// stroke first so a save mid-gesture keeps it.
pub fn serialize() ?[]u8 {
    _ = endStrokeUnit();
    if (g_strokes.items.len == 0) return null;
    var buf: std.ArrayList(u8) = .empty;
    writeBlob(&buf) catch {
        buf.deinit(alloc);
        return null;
    };
    return buf.toOwnedSlice(alloc) catch {
        buf.deinit(alloc);
        return null;
    };
}

// ── Load / apply ────────────────────────────────────────────────────────────────────
/// Peek the detail (paint density, texels/meter) a program was recorded at, without
/// replaying. The caller sets this detail FIRST (it rebuilds the atlas + re-uploads the
/// mesh, which this module can't) before calling apply(). Null on a malformed blob.
pub fn programDetail(blob: []const u8) ?u16 {
    if (blob.len < 8) return null;
    if (!std.mem.eql(u8, blob[0..4], &MAGIC)) return null;
    const ver = std.mem.readInt(u16, blob[4..6], .little);
    if (ver < 1 or ver > VERSION) return null;
    return std.mem.readInt(u16, blob[6..8], .little);
}

// Parse the shared material table into the LIVE g_mats (the loaded program is adopted as
// the live program, req_2529 — painting more must append to it).
fn parseMats(c: *Cursor) bool {
    const mat_count = c.u16v() orelse return false;
    var mi: u16 = 0;
    while (mi < mat_count) : (mi += 1) {
        const klen = c.u16v() orelse return false;
        const key = c.bytes(klen) orelse return false;
        const wlen = c.u32v() orelse return false;
        const wgsl = c.bytes(wlen) orelse return false;
        const dlen = c.u16v() orelse return false;
        const data = alloc.alloc(f32, dlen) catch return false;
        var di: u16 = 0;
        while (di < dlen) : (di += 1) data[di] = c.f32v() orelse {
            alloc.free(data);
            return false;
        };
        const tiles = c.f32v() orelse {
            alloc.free(data);
            return false;
        };
        const k = alloc.dupe(u8, key) catch {
            alloc.free(data);
            return false;
        };
        const w = alloc.dupe(u8, wgsl) catch {
            alloc.free(k);
            alloc.free(data);
            return false;
        };
        g_mats.append(alloc, .{ .key = k, .wgsl = w, .data = data, .tiles = tiles }) catch {
            alloc.free(k);
            alloc.free(w);
            alloc.free(data);
            return false;
        };
    }
    return true;
}

// Convert a v1 flat op stream (face-indexed) into ONE v2 stroke keyed against the
// CURRENT mesh — the migration the hide-stable keys need. v1 replay used raw face
// indices on this same mesh, so mapping each index through faceKeyOf preserves exactly
// the faces v1 would have painted, while making the result hide-stable from here on.
fn convertV1OpsInner(ops: []const u8, out: *std.ArrayList(u8)) !void {
    var c = Cursor{ .b = ops };
    while (c.p < c.b.len) {
        const tag = c.u8v() orelse break;
        switch (tag) {
            OP_INK_COLOR => {
                const cc = c.bytes(3) orelse return error.Malformed;
                try out.append(alloc, OP_INK_COLOR);
                try out.appendSlice(alloc, cc);
            },
            OP_INK_MATERIAL => {
                const idx = c.u16v() orelse return error.Malformed;
                try out.append(alloc, OP_INK_MATERIAL);
                try out.appendSlice(alloc, &u16le(idx));
            },
            OP_DAB => {
                const face = c.u32v() orelse return error.Malformed;
                const u = c.u32v() orelse return error.Malformed;
                const v = c.u32v() orelse return error.Malformed;
                const radius = c.u32v() orelse return error.Malformed;
                const flow = c.u32v() orelse return error.Malformed;
                const key = faceKeyOf(face);
                try out.append(alloc, OP_DAB);
                try out.appendSlice(alloc, &u32le(key.group));
                try out.appendSlice(alloc, &u32le(key.ord));
                try out.appendSlice(alloc, &u32le(u));
                try out.appendSlice(alloc, &u32le(v));
                try out.appendSlice(alloc, &u32le(radius));
                try out.appendSlice(alloc, &u32le(flow));
            },
            OP_FILL => {
                const face = c.u32v() orelse return error.Malformed;
                const key = faceKeyOf(face);
                try out.append(alloc, OP_FILL);
                try out.appendSlice(alloc, &u32le(key.group));
                try out.appendSlice(alloc, &u32le(key.ord));
            },
            else => return error.Malformed,
        }
    }
}

fn convertV1Ops(ops: []const u8) ?[]u8 {
    var out: std.ArrayList(u8) = .empty;
    convertV1OpsInner(ops, &out) catch {
        out.deinit(alloc);
        return null;
    };
    return out.toOwnedSlice(alloc) catch {
        out.deinit(alloc);
        return null;
    };
}

/// Rebuild the atlas by replaying a serialized program, ADOPTING it as the live recorded
/// program (req_2529: painting more appends; a later save returns the cumulative work).
/// v2 blobs restore their layer table; v1 blobs load as one "Layer 1" stroke. The caller
/// must have already set the program's detail (see programDetail). The stroke journal
/// starts fresh — the loaded painting is the new floor, not an undoable unit.
pub fn apply(io: std.Io, environ: *const std.process.Environ.Map, blob: []const u8) bool {
    var c = Cursor{ .b = blob };
    const magic = c.bytes(4) orelse return false;
    if (!std.mem.eql(u8, magic, &MAGIC)) return false;
    const ver = c.u16v() orelse return false;
    if (ver < 1 or ver > VERSION) return false;
    _ = c.u16v() orelse return false; // detail (applied by the caller before apply)
    _ = c.u32v() orelse return false; // facecount (advisory)

    dropLayerCarry(); // the loaded program's table wins over any pending edit carry
    reset();
    if (!applyParse(&c, ver, blob)) {
        reset(); // never leave a half-adopted program behind a failed load
        return false;
    }

    // Prepare the canvas: the caller already set detail (a mesh re-upload); a replayed
    // painting HAS a base (it was created with one), so activate it before the clear lays
    // it back under the strokes (req_2551). The post-clear atlas is the undo baseline.
    model_paint.activateBase();
    model_paint.clearAtlas();
    forceBaselineCapture();
    replayAll(io, environ);
    return true;
}

/// Adopt a serialized program while preserving the atlas already resident as its
/// baseline. Package restore uses this after loading raster-base.png; ordinary
/// apply() deliberately reconstructs the generated base instead.
pub fn applyOverCurrentBaseline(io: std.Io, environ: *const std.process.Environ.Map, blob: []const u8) bool {
    var c = Cursor{ .b = blob };
    const magic = c.bytes(4) orelse return false;
    if (!std.mem.eql(u8, magic, &MAGIC)) return false;
    const ver = c.u16v() orelse return false;
    if (ver < 1 or ver > VERSION) return false;
    _ = c.u16v() orelse return false;
    _ = c.u32v() orelse return false;

    dropLayerCarry();
    reset();
    if (!applyParse(&c, ver, blob)) {
        reset();
        return false;
    }
    forceBaselineCapture();
    replayAll(io, environ);
    return true;
}

// Parse the mats + layers + strokes of a blob into the (already reset) live state.
// Any false return leaves partial state — apply() resets it.
fn applyParse(c: *Cursor, ver: u16, blob: []const u8) bool {
    if (!parseMats(c)) return false;
    if (ver == 1) {
        _ = c.u32v() orelse return false; // ops byte length (advisory; read to blob end)
        ensureLayers();
        const ops = convertV1Ops(blob[c.p..]) orelse return false;
        if (ops.len > 0) {
            g_strokes.append(alloc, .{ .layer = g_active_layer, .ops = ops }) catch {
                alloc.free(ops);
                return false;
            };
        } else {
            alloc.free(ops);
        }
        return true;
    }
    const layer_count = c.u16v() orelse return false;
    var li: u16 = 0;
    var max_id: u32 = 0;
    while (li < layer_count) : (li += 1) {
        const id = c.u32v() orelse return false;
        const vis = c.u8v() orelse return false;
        const nlen = c.u16v() orelse return false;
        const name = c.bytes(nlen) orelse return false;
        const nm = alloc.dupe(u8, name) catch return false;
        g_layers.append(alloc, .{ .id = id, .name = nm, .visible = vis != 0 }) catch {
            alloc.free(nm);
            return false;
        };
        if (id > max_id) max_id = id;
    }
    g_active_layer = c.u32v() orelse return false;
    g_next_layer_id = max_id + 1;
    if (g_layers.items.len == 0) ensureLayers();
    if (layerIndexOf(g_active_layer) == null) g_active_layer = g_layers.items[g_layers.items.len - 1].id;
    const stroke_count = c.u32v() orelse return false;
    var si: u32 = 0;
    while (si < stroke_count) : (si += 1) {
        const layer = c.u32v() orelse return false;
        const olen = c.u32v() orelse return false;
        const ops_src = c.bytes(olen) orelse return false;
        const ops = alloc.dupe(u8, ops_src) catch return false;
        g_strokes.append(alloc, .{ .layer = layer, .ops = ops }) catch {
            alloc.free(ops);
            return false;
        };
    }
    return true;
}

// ── Per-document session (req_3850) ────────────────────────────────────────
// The editable paint recipe is document state just as surely as the atlas pixels in
// model_paint. Before this owner existed, 3d.zig parked the raster with each model but
// left this module's layers, strokes, history, baseline, and material recipes in one
// process-global slot. An A→B→A switch could therefore show A's pixels with B's
// editing history — a visually plausible split authority that failed only on the next
// undo, replay, or save.
//
// Park and load are ownership-neutral VALUE moves, matching mesh_edit, model_source,
// and model_paint. Pointer fields are not cloned and are not freed: the parked record
// becomes their sole authority only after the coordinator resets or loads the globals.
// The record for the active document is merely an alias and is overwritten on the next
// park. Every `g_*` below is included deliberately, including an open stroke and the
// one-shot topology carries; silently leaving either process-global would splice the
// next gesture or replacement into whichever document happened to become active.
pub const Session = struct {
    g_layers: @TypeOf(g_layers) = .empty,
    g_active_layer: @TypeOf(g_active_layer) = 0,
    g_next_layer_id: @TypeOf(g_next_layer_id) = 1,
    g_strokes: @TypeOf(g_strokes) = .empty,
    g_mats: @TypeOf(g_mats) = .empty,
    g_open: @TypeOf(g_open) = .empty,
    g_open_live: @TypeOf(g_open_live) = false,
    g_open_label: @TypeOf(g_open_label) = "stroke",
    g_open_fill_seen: @TypeOf(g_open_fill_seen) = .{},
    g_have_active: @TypeOf(g_have_active) = false,
    g_active_is_mat: @TypeOf(g_active_is_mat) = false,
    g_active_mat: @TypeOf(g_active_mat) = 0,
    g_active_rgb: @TypeOf(g_active_rgb) = .{ 0, 0, 0 },
    g_recording: @TypeOf(g_recording) = true,
    g_baseline: @TypeOf(g_baseline) = null,
    g_ord_cache: @TypeOf(g_ord_cache) = null,
    g_carry_layers: @TypeOf(g_carry_layers) = null,
    g_carry_active: @TypeOf(g_carry_active) = 0,
    g_carry_next: @TypeOf(g_carry_next) = 1,
    g_carry_program_once: @TypeOf(g_carry_program_once) = false,
    g_undo_snaps: @TypeOf(g_undo_snaps) = .empty,
    g_redo_snaps: @TypeOf(g_redo_snaps) = .empty,
};

pub fn sessionSave(session: *Session) void {
    inline for (@typeInfo(Session).@"struct".fields) |field|
        @field(session, field.name) = @field(@This(), field.name);
}

pub fn sessionLoad(session: *const Session) void {
    inline for (@typeInfo(Session).@"struct".fields) |field|
        @field(@This(), field.name) = @field(session, field.name);
}

pub fn sessionReset() void {
    const fresh = Session{};
    inline for (@typeInfo(Session).@"struct".fields) |field|
        @field(@This(), field.name) = @field(fresh, field.name);
    // Deliberately frees NOTHING: ownership of the previous state lives in the
    // record the coordinator just parked.
}

/// Destroy one genuinely parked record. Calling this for the active record while its
/// pointers are still installed in globals would be a use-after-free; the model-session
/// registry first parks the active globals and resets them before invoking this hook.
/// Resetting the record afterward makes the operation idempotent and keeps an aborted
/// registry teardown from retaining stale aliases.
pub fn sessionDeinitParked(session: *Session) void {
    freeLayerList(&session.g_layers);
    session.g_layers.deinit(alloc);
    freeStrokeList(&session.g_strokes);
    session.g_strokes.deinit(alloc);
    freeMatList(&session.g_mats);
    session.g_mats.deinit(alloc);
    session.g_open.deinit(alloc);
    session.g_open_fill_seen.deinit(alloc);
    if (session.g_baseline) |pixels| alloc.free(pixels);
    if (session.g_ord_cache) |ordinals| alloc.free(ordinals);
    if (session.g_carry_layers) |layers| {
        for (layers) |layer| alloc.free(layer.name);
        alloc.free(layers);
    }
    freeSnapshotStack(&session.g_undo_snaps);
    session.g_undo_snaps.deinit(alloc);
    freeSnapshotStack(&session.g_redo_snaps);
    session.g_redo_snaps.deinit(alloc);
    session.* = .{};
}
